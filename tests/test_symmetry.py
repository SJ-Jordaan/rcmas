Pair = tuple[tuple[int, ...], tuple[int, ...]]  # (final owner, first-round actions)


def regions_of(owner: Sequence[int], n: int) -> list[list[int]]:
    return [[i for i, o in enumerate(owner) if o == a] for a in range(n)]


def satisfying_pairs(
    territory: Territory, n: int, demands: Sequence[int] | None = None
) -> Iterator[tuple[tuple[int, ...], tuple[int, ...], tuple[int, ...]]]:
    """Every satisfying play as (final owner, first-round actions, rewards),
    at the horizon m = |T| // n."""
    S = len(territory)
    m = S // n
    d = tuple(demands) if demands is not None else (0,) * n
    nbrs = territory.neighbor_map()
    for owner in final_states(S, n, m):
        r = rewards_from_owner(owner, n, nbrs)
        if any(r[a] < d[a] for a in range(n)):
            continue
        for opens in itertools.product(*regions_of(owner, n)):
            yield owner, opens, r


def relabel_sorted(
    classes: Sequence[Sequence[int]], owner: Sequence[int], opens: Sequence[int]
) -> Pair:
    """The image under the agent permutation that sorts the first-round
    actions within each class (the relabelling of Lemma 5.1.2)."""
    rho: dict[int, int] = {}
    for cls in classes:
        for new, old in zip(cls, sorted(cls, key=lambda a: opens[a])):
            rho[old] = new
    new_owner = tuple(rho[o] if o != UNOWNED else UNOWNED for o in owner)
    new_opens = [0] * len(opens)
    for a, o in enumerate(opens):
        new_opens[rho[a]] = o
    return new_owner, tuple(new_opens)


def act(h: Sequence[int], owner: Sequence[int], opens: Sequence[int]) -> Pair:
    """The image under the territory map h (Definition 5.1.4: s'(h(i)) = s(i))."""
    new_owner = [UNOWNED] * len(owner)
    for i, o in enumerate(owner):
        new_owner[h[i]] = o
    return tuple(new_owner), tuple(h[o] for o in opens)


def group_closure(
    generators: Sequence[dict[int, int]], S: int
) -> list[tuple[int, ...]]:
    """All elements of the permutation group generated by *generators*."""
    gens = [tuple(g[i] for i in range(S)) for g in generators]
    ident = tuple(range(S))
    seen = {ident}
    frontier = [ident]
    while frontier:
        nxt = []
        for p in frontier:
            for g in gens:
                q = tuple(g[p[i]] for i in range(S))
                if q not in seen:
                    seen.add(q)
                    nxt.append(q)
        frontier = nxt
    return sorted(seen)


def tool_group(territory: Territory) -> list[tuple[int, ...]]:
    """The group H of the spatial constraint: H_geo for a connected
    territory, the group of Theorem 5.3.2 for a disconnected one."""
    S = len(territory)
    if len(territory_connected_components(territory)) > 1:
        return group_closure(component_info(territory).generators, S)
    return [tuple(h[i] for i in range(S)) for h in geometric_automorphisms(territory)]


def is_automorphism(territory: Territory, perm: Sequence[int]) -> bool:
    nbrs = territory.neighbor_map()
    S = len(territory)
    if sorted(perm) != list(range(S)):
        return False
    return all(
        (j in nbrs[i]) == (perm[j] in nbrs[perm[i]]) for i in range(S) for j in range(S)
    )


def orbit_report(
    territory: Territory, n: int, demands: Sequence[int] | None, plan: SymmetryBreaking
) -> dict[str, object]:
    """Check Theorem 5.1.3 / 5.3.2 on the satisfying plays by enumeration.

    Returns the number of G_H-orbits of satisfying pairs without a member
    that the plan admits, the best collective reward with and without the
    constraints, and the class-sorted reward profiles with and without them.
    """
    group = tool_group(territory)
    classes = plan.classes
    seen: set[Pair] = set()
    failures = 0
    best_all = best_adm = None
    prof_all: set[tuple] = set()
    prof_adm: set[tuple] = set()
    for owner, opens, r in satisfying_pairs(territory, n, demands):
        total = sum(r)
        prof = tuple(tuple(sorted(r[a] for a in cls)) for cls in classes)
        best_all = total if best_all is None else max(best_all, total)
        prof_all.add(prof)
        if plan.admits(opens, owner):
            best_adm = total if best_adm is None else max(best_adm, total)
            prof_adm.add(prof)
        key = relabel_sorted(classes, owner, opens)
        if key in seen:
            continue
        seen.add(key)
        if not any(
            plan.admits(img[1], img[0])
            for img in (relabel_sorted(classes, *act(h, *key)) for h in group)
        ):
            failures += 1
    return {
        "orbit_failures": failures,
        "best_all": best_all,
        "best_admitted": best_adm,
        "profiles_all": prof_all,
        "profiles_admitted": prof_adm,
        "orbits_checked": len(seen),
    }


def dominated(p: tuple, q: tuple) -> bool:
    """True if the class-sorted profile q is at least p in every entry."""
    return all(all(y >= x for x, y in zip(pc, qc)) for pc, qc in zip(p, q))


def all_pairs(S: int, n: int, m: int, limit: int, seed: int = 0) -> list[Pair]:
    """Every (final state, first-round actions) pair, or *limit* random ones."""
    out: list[Pair] = []
    for owner in final_states(S, n, m):
        for opens in itertools.product(*regions_of(owner, n)):
            out.append((owner, opens))
            if len(out) > limit:
                break
        if len(out) > limit:
            break
    if len(out) <= limit:
        return out
    rng = random.Random(seed)
    labels = [a for a in range(n) for _ in range(m)] + [UNOWNED] * (S - n * m)
    sample = []
    for _ in range(limit):
        rng.shuffle(labels)
        owner = tuple(labels)
        sample.append((owner, tuple(rng.choice(reg) for reg in regions_of(owner, n))))
    return sample


def z3_evaluator(exprs: Sequence[object]):
    """Compile Z3 constraints over Int constants into a Python predicate on
    an environment {name: value}."""
    import z3

    def comp(e):
        if z3.is_true(e):
            return lambda env: True
        if z3.is_false(e):
            return lambda env: False
        if z3.is_int_value(e):
            val = e.as_long()
            return lambda env: val
        if z3.is_const(e):
            name = str(e)
            return lambda env: env[name]
        k = e.decl().kind()
        ch = [comp(c) for c in e.children()]
        if k == z3.Z3_OP_AND:
            return lambda env: all(c(env) for c in ch)
        if k == z3.Z3_OP_OR:
            return lambda env: any(c(env) for c in ch)
        if k == z3.Z3_OP_NOT:
            return lambda env: not ch[0](env)
        if k == z3.Z3_OP_IMPLIES:
            return lambda env: (not ch[0](env)) or ch[1](env)
        if k == z3.Z3_OP_EQ:
            return lambda env: ch[0](env) == ch[1](env)
        if k == z3.Z3_OP_DISTINCT:
            return lambda env: len({c(env) for c in ch}) == len(ch)
        if k == z3.Z3_OP_LE:
            return lambda env: ch[0](env) <= ch[1](env)
        if k == z3.Z3_OP_LT:
            return lambda env: ch[0](env) < ch[1](env)
        if k == z3.Z3_OP_GE:
            return lambda env: ch[0](env) >= ch[1](env)
        if k == z3.Z3_OP_GT:
            return lambda env: ch[0](env) > ch[1](env)
        raise NotImplementedError(str(e))

    fs = [comp(e) for e in exprs]
    return lambda env: all(f(env) for f in fs)


class Collector:
    """Stands in for a solver: records the constraints passed to ``add``."""

    def __init__(self) -> None:
        self.exprs: list[object] = []

    def add(self, *exprs: object) -> None:
        self.exprs.extend(exprs)


def smt_symmetry_predicate(territory: Territory, n: int, demands: Sequence[int] | None):
    """The constraints of :func:`rcmas.smt_solve.symmetry_constraints` as a
    Python predicate on (final owner, first-round actions)."""
    pytest.importorskip("z3")
    from rcmas.smt_solve import symmetry_constraints
    from rcmas.smt_variables import create_variables

    m = len(territory) // n
    v = create_variables(territory, n, m)
    col = Collector()
    symmetry_constraints(
        col, v, territory, tuple(demands) if demands is not None else None
    )
    ev = z3_evaluator(col.exprs)

    def pred(owner: Sequence[int], opens: Sequence[int]) -> bool:
        env = {f"action_{a}_0": o for a, o in enumerate(opens)}
        env.update({f"owner_{i}_{m}": o for i, o in enumerate(owner)})
        return ev(env)

    return pred


