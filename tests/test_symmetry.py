class TestSynthesisWithSymmetry:
    @pytest.mark.parametrize(
        "name,n,demands",
        [
            ("3x3", 2, (3, 3)),
            ("3x3", 3, (2, 2, 3)),
            ("3x3", 3, (3, 3, 3)),
            ("4x2", 2, None),
            ("4x2", 4, (2, 1, 1, 2)),
        ],
    )
    def test_optimum_and_model_respect_constraints(self, name: str, n: int, demands):
        """smt(F and [Sym], f) has the optimum of smt(F, f) (Corollary 5.1.4),
        and its model meets the constraints of the plan."""
        pytest.importorskip("z3")
        from rcmas.smt_solve import solve_collective_optimality

        t = grid(name)
        m = len(t) // n
        plain = solve_collective_optimality(
            territory=t, num_agents=n, horizon=m, demands=demands
        )
        sym = solve_collective_optimality(
            territory=t,
            num_agents=n,
            horizon=m,
            demands=demands,
            symmetry_breaking=True,
        )
        assert plain.is_sat == sym.is_sat
        if not plain.is_sat:
            return
        assert sum(sym.payoff_by_agent) == sum(plain.payoff_by_agent)
        plan = symmetry_breaking_plan(t, n, demands)
        assert plan.admits(sym.play.actions[0], sym.play.final_state)

    def test_unsatisfiable_stays_unsatisfiable(self):
        """Demands above m: no satisfying play with or without the constraints."""
        pytest.importorskip("z3")
