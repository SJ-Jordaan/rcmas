class TestReductionCounts:
    """Corollary 5.1.5 on the assignments of distinct first-round actions."""

    @pytest.mark.parametrize(
        "name,demands", [("3x3", (0, 0)), ("4x2", (1, 1, 2)), ("3x2", (0, 0, 0))]
    )
    def test_fractions(self, name: str, demands: tuple[int, ...]):
        t = grid(name)
        n, S = len(demands), len(t)
        plan = symmetry_breaking_plan(t, n, demands)
        assignments = list(itertools.permutations(range(S), n))
        lex = sum(plan.lex_leader_holds(o) for o in assignments)
        spatial = sum(o[0] in plan.representatives for o in assignments)
        p_d = 1
        for cls in plan.classes:
            for k in range(2, len(cls) + 1):
                p_d *= k
        assert lex * p_d == len(assignments)
        assert spatial * S == len(assignments) * len(symmetry_info(t).orbits)


