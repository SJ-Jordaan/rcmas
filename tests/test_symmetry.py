def _brute_force_aut(territory: Territory) -> set[tuple[int, ...]]:
    S = len(territory)
    return {
        p for p in itertools.permutations(range(S)) if is_automorphism(territory, p)
    }


class TestGeometricSubgroup:
    @pytest.mark.parametrize(
        "name", ["2x2", "3x2", "4x2", "3x3", "bent-path", "L-small", "2x2-2x2"]
    )
    def test_elements_are_automorphisms(self, name: str):
        t = grid(name)
        for h in geometric_automorphisms(t):
            assert is_automorphism(t, [h[i] for i in range(len(t))])

    def test_alias(self, territory_3x3: Territory):
        assert territory_automorphisms(territory_3x3) == geometric_automorphisms(
            territory_3x3
        )

    @pytest.mark.parametrize("name", ["2x2", "3x2", "bent-path", "L-small"])
    def test_subgroup_of_aut(self, name: str):
        """H_geo <= Aut(T), computed here by trying every permutation."""
        t = grid(name)
        aut = _brute_force_aut(t)
        geo = {tuple(h[i] for i in range(len(t))) for h in geometric_automorphisms(t)}
        assert geo <= aut

    def test_bent_path_geometric_group_is_trivial(self):
        """Section 5.1.1: the bent path has H_geo = {id} and |Aut(T)| = 2."""
        # The bent path {(1,1), (2,1), (3,1), (3,2)} of Section 5.1.1.
        t = Territory.from_ascii(["##.", "..."])
        assert len(t) == 4
        assert len(geometric_automorphisms(t)) == 1
        assert len(_brute_force_aut(t)) == 2

    def test_full_grids_reach_aut(self):
        """H_geo = Aut(T) on full grids: D_4 on squares, V_4 on rectangles."""
        assert (
            len(geometric_automorphisms(grid("2x2")))
            == len(_brute_force_aut(grid("2x2")))
            == 8
        )
        assert (
            len(geometric_automorphisms(grid("3x2")))
            == len(_brute_force_aut(grid("3x2")))
            == 4
        )


